#!/usr/bin/env python3
"""Regenerate tools/icon_data.py from the official icon packages.

The generated module is committed so that `tools/build.py` keeps working with the
Python standard library only. Icons are copied from their upstream releases:

- Font Awesome Free 7 (`@fortawesome/fontawesome-free`, CC BY 4.0 for icons):
  interface icons such as arrows, download, envelope, award, handshake.
- Simple Icons 16 (`simple-icons`, CC0 1.0): official technology and network
  brand marks (HTML5, CSS, JavaScript, React, Vue.js, PHP, Python, Kotlin,
  Android, Git, GitHub, Linux).

Usage (development only, never needed to build or deploy the site):

    npm pack @fortawesome/fontawesome-free simple-icons
    mkdir -p /tmp/icons && tar xzf fortawesome-fontawesome-free-*.tgz -C /tmp/icons
    tar xzf simple-icons-*.tgz -C /tmp/icons
    python3 tools/sync_icons.py /tmp/icons

Both packages ship attribution files; the licences are recorded in
assets/icons/LICENSE.md and quoted in the generated module header.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tools" / "icon_data.py"

# Font Awesome Free 7 interface icons used by the site.
FA_SOLID = {
    "arrow-right": "Continuation and next action",
    "arrow-left": "Previous and back",
    "arrow-up": "Back to top",
    "arrow-down": "Scroll to the next block",
    "arrow-up-right-from-square": "External destination or new tab",
    "download": "Downloads",
    "circle-info": "Information and caveats",
    "circle-check": "Published status",
    "xmark": "Close",
    "check": "Confirmed fact",
    "envelope": "Email",
    "location-dot": "Location",
    "sun": "Light theme",
    "moon": "Dark theme",
    "laptop-code": "Web development service",
    "mobile-screen": "Android service and application",
    "handshake": "Partnership and support",
    "users": "Collective and team",
    "terminal": "Systems and practices",
    "award": "Certification",
    "universal-access": "Web accessibility",
    "code": "Code",
    "pause": "Pause the orbits",
    "play": "Resume the orbits",
    "layer-group": "Layered content and preview",
    "file-arrow-down": "Document download",
}

FA_BRANDS = {
    "whatsapp": "WhatsApp contact",
    "facebook-f": "Facebook profile",
}

# Simple Icons slugs used for the skill satellites, with the display name
# declared in src/data/skills.json.
SIMPLE_ICONS = {
    "html5": "HTML5",
    "css": "CSS3",
    "javascript": "JavaScript",
    "react": "React",
    "vuedotjs": "Vue.js",
    "php": "PHP",
    "python": "Python",
    "kotlin": "Kotlin",
    "android": "Android",
    "git": "Git",
    "github": "GitHub",
    "linux": "Linux",
}


def clean(svg: str) -> tuple[str, str]:
    """Return (viewBox, inner markup) for an upstream SVG file."""
    view_box = re.search(r'viewBox="([^"]+)"', svg)
    if not view_box:
        raise SystemExit("SVG without viewBox")
    inner = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
    inner = re.sub(r"^.*?<svg[^>]*>", "", inner, flags=re.S)
    inner = re.sub(r"</svg>\s*$", "", inner, flags=re.S)
    inner = inner.replace(' fill="currentColor"', "")
    inner = re.sub(r"\s+", " ", inner).strip()
    return view_box.group(1), inner


def main(source: Path) -> None:
    fa = source / "fortawesome-fontawesome-free-7.3.1" / "package" / "svgs"
    simple = source / "simple-icons-16.36.0" / "package" / "icons"
    if not fa.is_dir() or not simple.is_dir():
        raise SystemExit(f"Extracted packages not found under {source}")

    entries: dict[str, tuple[str, str, str]] = {}
    for name, note in FA_SOLID.items():
        path = fa / "solid" / f"{name}.svg"
        if not path.is_file():
            raise SystemExit(f"Missing Font Awesome solid icon: {name}")
        view_box, inner = clean(path.read_text(encoding="utf-8"))
        entries[f"fa-{name}"] = (view_box, inner, f"Font Awesome Free 7 solid — {note}")
    for name, note in FA_BRANDS.items():
        path = fa / "brands" / f"{name}.svg"
        if not path.is_file():
            raise SystemExit(f"Missing Font Awesome brand icon: {name}")
        view_box, inner = clean(path.read_text(encoding="utf-8"))
        entries[f"fa-{name}"] = (view_box, inner, f"Font Awesome Free 7 brands — {note}")
    for name, note in SIMPLE_ICONS.items():
        path = simple / f"{name}.svg"
        if not path.is_file():
            raise SystemExit(f"Missing Simple Icons icon: {name}")
        view_box, inner = clean(path.read_text(encoding="utf-8"))
        entries[f"brand-{name}"] = (view_box, inner, f"Simple Icons 16 — {note}")

    lines = [
        '"""Generated by tools/sync_icons.py. Do not edit by hand.',
        "",
        "Official icon artwork vendored for the inline SVG sprite:",
        "- Font Awesome Free 7 (icons CC BY 4.0, fonts SIL OFL 1.1, code MIT);",
        "- Simple Icons 16 (CC0 1.0).",
        "",
        "Each value is (viewBox, inner markup, attribution).",
        '"""',
        "",
        "ICON_LIBRARY = {",
    ]
    for key, (view_box, inner, note) in entries.items():
        lines.append(f"    {key!r}: (")
        lines.append(f"        {view_box!r},")
        lines.append(f"        {inner!r},")
        lines.append(f"        {note!r},")
        lines.append("    ),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(entries)} icons")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(Path(sys.argv[1]).resolve())
